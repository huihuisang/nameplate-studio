async function addImageLayer(file) {
  if (!file) return;
  const objectUrl = URL.createObjectURL(file);
  const image = new Image();
  try {
    await new Promise((resolve, reject) => {
      image.addEventListener("load", resolve, { once: true });
      image.addEventListener("error", reject, { once: true });
      image.src = objectUrl;
    });
    const layer = {
      id: `layer-${nextLayerId++}`,
      type: "image",
      role: null,
      label: file.name,
      visible: true,
      image,
      objectUrl,
      aspectRatio: image.naturalWidth / image.naturalHeight,
      x: CANVAS_SIZE / 2,
      y: PANEL_HEIGHT / 2,
      width: Math.min(520, image.naturalWidth),
      opacity: 100,
    };
    layers.push(layer);
    selectLayer(layer.id);
    setStatus("imageAdded");
  } catch (error) {
    console.error(error);
    URL.revokeObjectURL(objectUrl);
    setStatus("fileError");
  }
}

function duplicateSelectedLayer() {
  const layer = getSelectedLayer();
  if (!layer) return;
  const copy = {
    ...layer,
    id: `layer-${nextLayerId++}`,
    role: null,
    label: `${getLayerName(layer)} copy`,
    x: layer.x + 45,
    y: layer.y + 45,
    shadow: layer.type === "text" ? { ...layer.shadow } : undefined,
  };
  clampLayer(copy);
  layers.push(copy);
  selectLayer(copy.id);
}

function deleteSelectedLayer() {
  const index = layers.findIndex((layer) => layer.id === selectedLayerId);
  if (index < 0) return;
  const [removed] = layers.splice(index, 1);
  if (removed.type === "image" && removed.objectUrl) URL.revokeObjectURL(removed.objectUrl);
  selectedLayerId = layers[Math.min(index, layers.length - 1)]?.id ?? null;
  renderLayerList();
  syncInspector();
  render();
}

function moveSelectedLayer(direction) {
  const index = layers.findIndex((layer) => layer.id === selectedLayerId);
  const nextIndex = index + direction;
  if (index < 0 || nextIndex < 0 || nextIndex >= layers.length) return;
  [layers[index], layers[nextIndex]] = [layers[nextIndex], layers[index]];
  renderLayerList();
  render();
}

function reset() {
  layers.forEach((layer) => {
    if (layer.type === "image" && layer.objectUrl) URL.revokeObjectURL(layer.objectUrl);
  });
  layers = createDefaultLayers();
  selectedLayerId = layers[0].id;
  renderLayerList();
  syncInspector();
  render();
  setStatus("ready");
}

function canvasPoint(event) {
  const rect = editorCanvas.getBoundingClientRect();
  return {
    x: ((event.clientX - rect.left) / rect.width) * CANVAS_SIZE,
    y: ((event.clientY - rect.top) / rect.height) * PANEL_HEIGHT,
  };
}

function hitTest(point) {
  for (let index = layers.length - 1; index >= 0; index -= 1) {
    const layer = layers[index];
    if (!layer.visible) continue;
    const bounds = getLayerBounds(layer);
    if (
      point.x >= bounds.x
      && point.x <= bounds.x + bounds.width
      && point.y >= bounds.y
      && point.y <= bounds.y + bounds.height
    ) return layer;
  }
  return null;
}

function isPointNearLayerBorder(point, layer) {
  const bounds = getLayerBounds(layer);
  const tolerance = 42;
  const withinOuter = (
    point.x >= bounds.x - tolerance
    && point.x <= bounds.x + bounds.width + tolerance
    && point.y >= bounds.y - tolerance
    && point.y <= bounds.y + bounds.height + tolerance
  );
  const withinInner = (
    point.x > bounds.x + tolerance
    && point.x < bounds.x + bounds.width - tolerance
    && point.y > bounds.y + tolerance
    && point.y < bounds.y + bounds.height - tolerance
  );
  return withinOuter && !withinInner;
}

function positionCanvasLayerActions(layer) {
  const bounds = getLayerBounds(layer);
  const rect = editorCanvas.getBoundingClientRect();
  const scaleX = rect.width / CANVAS_SIZE;
  const scaleY = rect.height / PANEL_HEIGHT;
  const halfToolbarWidth = 90;
  const toolbarHeight = 43;
  const actionX = Math.max(
    halfToolbarWidth,
    Math.min(rect.width - halfToolbarWidth, (bounds.x + bounds.width / 2) * scaleX),
  );
  const above = bounds.y * scaleY - toolbarHeight - 10;
  const below = (bounds.y + bounds.height) * scaleY + 10;
  const actionY = above >= 8 ? above : Math.min(rect.height - toolbarHeight - 8, below);
  canvasLayerActions.style.left = `${actionX}px`;
  canvasLayerActions.style.top = `${actionY}px`;
}

function showCanvasLayerActions(layer) {
  window.clearTimeout(layerActionHideTimer);
  positionCanvasLayerActions(layer);
  canvasLayerActions.hidden = false;
}

function hideCanvasLayerActions(delay = 0) {
  window.clearTimeout(layerActionHideTimer);
  layerActionHideTimer = window.setTimeout(() => {
    canvasLayerActions.hidden = true;
  }, delay);
}

editorCanvas.addEventListener("pointerdown", (event) => {
  const point = canvasPoint(event);
  const layer = hitTest(point);
  if (!layer) return;
  selectLayer(layer.id);
  dragState = { offsetX: point.x - layer.x, offsetY: point.y - layer.y };
  editorCanvas.setPointerCapture(event.pointerId);
});

editorCanvas.addEventListener("pointermove", (event) => {
  const point = canvasPoint(event);
  if (!dragState) {
    const layer = getSelectedLayer();
    if (layer?.visible && isPointNearLayerBorder(point, layer)) {
      showCanvasLayerActions(layer);
    } else {
      hideCanvasLayerActions(120);
    }
    return;
  }

  const layer = getSelectedLayer();
  if (!layer) return;
  layer.x = point.x - dragState.offsetX;
  layer.y = point.y - dragState.offsetY;
  clampLayer(layer);
  controls.x.value = Math.round(layer.x);
  controls.y.value = Math.round(layer.y);
  render();
});

editorCanvas.addEventListener("pointerleave", () => hideCanvasLayerActions(120));
canvasLayerActions.addEventListener("pointerenter", () => window.clearTimeout(layerActionHideTimer));
