async function loadCustomFont(file) {
  if (!file) return;
  if (uploadedFontUrl) URL.revokeObjectURL(uploadedFontUrl);
  uploadedFontUrl = URL.createObjectURL(file);
  const family = `Custom Font ${Date.now()}`;
  try {
    const fontFace = new FontFace(family, `url(${uploadedFontUrl})`);
    await fontFace.load();
    document.fonts.add(fontFace);
    const option = document.createElement("option");
    option.value = family;
    option.textContent = file.name;
    controls.font.append(option);
    const layer = getSelectedLayer();
    if (layer?.type === "text") {
      layer.font = family;
      controls.font.value = family;
      render();
    }
    setStatus("fontLoaded", { name: file.name });
  } catch (error) {
    console.error(error);
    setStatus("fileError");
  }
}

function createFontOption(family, label = family) {
  const option = document.createElement("option");
  option.value = family;
  option.textContent = label;
  return option;
}

async function loadSystemFonts() {
  if (!window.queryLocalFonts) {
    setStatus("systemFontsUnavailable");
    return;
  }

  try {
    const fontData = await window.queryLocalFonts();
    const families = [...new Set(fontData.map((font) => font.family).filter(Boolean))]
      .sort((first, second) => first.localeCompare(second));
    const existing = new Set([...controls.font.options].map((option) => option.value));
    const oldGroup = controls.font.querySelector("optgroup[data-system-fonts]");
    oldGroup?.remove();

    const group = document.createElement("optgroup");
    group.label = "System Fonts";
    group.dataset.systemFonts = "true";
    families.filter((family) => !existing.has(family)).forEach((family) => {
      group.append(createFontOption(family));
    });
    controls.font.append(group);
    systemFontsLoaded = true;
    setStatus("systemFontsLoaded", { count: families.length });
  } catch (error) {
    console.warn("System font access was not granted.", error);
    setStatus(error.name === "NotAllowedError" ? "systemFontsDenied" : "systemFontsUnavailable");
  }
}

function getColumnLabel(index) {
  const header = batchHeaders[index] || `${t("content")} ${index + 1}`;
  return `${String.fromCharCode(65 + index)} — ${header}`;
}

function findSuggestedColumn(pattern, fallbackIndex) {
  const index = batchHeaders.findIndex((header) => pattern.test(header));
  return index >= 0 ? index : fallbackIndex;
}

function fillColumnSelect(select, selectedIndex) {
  select.replaceChildren();
  batchHeaders.forEach((_, index) => {
    const option = document.createElement("option");
    option.value = String(index);
    option.textContent = getColumnLabel(index);
    select.append(option);
  });
  select.value = String(Math.max(0, Math.min(selectedIndex, batchHeaders.length - 1)));
  select.disabled = batchHeaders.length === 0;
}

function updateBatchUi() {
  const hasData = batchRows.length > 0 && batchHeaders.length > 0;
  batchControls.nameColumn.disabled = !hasData;
  batchControls.numberColumn.disabled = !hasData;
  batchControls.exportButton.disabled = !hasData || !templateReady;
  batchControls.summary.textContent = hasData
    ? t("batchReady").replace("{count}", batchRows.length)
    : t("batchEmpty");
}

function spreadsheetRowsToData(rows) {
  const firstNonEmpty = rows.findIndex((row) => row.some((cell) => String(cell).trim() !== ""));
  if (firstNonEmpty < 0) return { headers: [], data: [] };

  const sourceHeaders = rows[firstNonEmpty];
  const widestRow = Math.max(...rows.slice(firstNonEmpty).map((row) => row.length));
  const headers = Array.from({ length: widestRow }, (_, index) => {
    const value = String(sourceHeaders[index] ?? "").trim();
    return value || `Column ${index + 1}`;
  });
  const data = rows
    .slice(firstNonEmpty + 1)
    .map((row) => headers.map((_, index) => String(row[index] ?? "").trim()))
    .filter((row) => row.some(Boolean));
  return { headers, data };
}

async function parseBatchFile(file) {
  if (!file || !window.XLSX) return;
  try {
    const workbook = XLSX.read(await file.arrayBuffer(), { type: "array", cellText: true });
    const sheet = workbook.Sheets[workbook.SheetNames[0]];
    const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: "", raw: false });
    const parsed = spreadsheetRowsToData(rows);
    batchHeaders = parsed.headers;
    batchRows = parsed.data;
    fillColumnSelect(batchControls.nameColumn, findSuggestedColumn(/name|姓名|名字/i, 0));
    fillColumnSelect(batchControls.numberColumn, findSuggestedColumn(/number|no\.?|编号|号码|序号/i, 1));
    updateBatchUi();
  } catch (error) {
    console.error(error);
    batchHeaders = [];
    batchRows = [];
    updateBatchUi();
    setStatus("sheetError");
  }
}

function canvasToBlob(sourceCanvas) {
  return new Promise((resolve, reject) => {
    sourceCanvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error("PNG encoding failed"))), "image/png");
  });
}

function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.style.display = "none";
  // Some browsers ignore clicks on detached download links.
  document.body.append(link);
  link.click();
  window.setTimeout(() => {
    link.remove();
    URL.revokeObjectURL(url);
  }, 3000);
}

function getBatchRecords() {
  const nameIndex = Number(batchControls.nameColumn.value);
  const numberIndex = Number(batchControls.numberColumn.value);
  if (!Number.isInteger(nameIndex) || !Number.isInteger(numberIndex)) return [];
  return batchRows
    .map((row) => ({ name: row[nameIndex] ?? "", number: row[numberIndex] ?? "" }))
    .filter((record) => record.name || record.number);
}

async function downloadBatchZip() {
  if (isFilePage) {
    setStatus("localServerRequired");
    return;
  }
  if (!window.JSZip) {
    setStatus("sheetError");
    return;
  }
  const nameLayer = layers.find((layer) => layer.role === "name");
  const numberLayer = layers.find((layer) => layer.role === "number");
  if (!nameLayer || !numberLayer) {
    setStatus("batchMissingLayers");
    return;
  }

  const records = getBatchRecords();
  if (records.length === 0) {
    setStatus("batchMissingColumns");
    return;
  }

  const originalText = { name: nameLayer.text, number: numberLayer.text };
  const zip = new JSZip();
  batchControls.exportButton.disabled = true;
  batchControls.progress.hidden = false;
  batchControls.progress.max = records.length;
  batchControls.progress.value = 0;

  try {
    for (const [index, record] of records.entries()) {
      nameLayer.text = record.name;
      numberLayer.text = record.number;
      render();
      const blob = await canvasToBlob(canvas);
      const indexPart = String(index + 1).padStart(3, "0");
      const filename = `${indexPart}-${safeFilenamePart(record.name, "name")}-${safeFilenamePart(record.number, "number")}.png`;
      zip.file(filename, blob);
      batchControls.progress.value = index + 1;
      setStatus("batchProcessing", { current: index + 1, total: records.length });
      await new Promise((resolve) => window.requestAnimationFrame(resolve));
    }

    nameLayer.text = originalText.name;
    numberLayer.text = originalText.number;
    render();
    setStatus("batchZipping");
    const archive = await zip.generateAsync(
      { type: "blob", compression: "DEFLATE", compressionOptions: { level: 6 } },
      (metadata) => {
        batchControls.progress.max = 100;
        batchControls.progress.value = metadata.percent;
      },
    );
    downloadBlob(archive, `nameplates-${new Date().toISOString().slice(0, 10)}.zip`);
    setStatus("batchDone", { count: records.length });
  } catch (error) {
    console.error(error);
    nameLayer.text = originalText.name;
    numberLayer.text = originalText.number;
    render();
    setStatus("fileError");
  } finally {
    batchControls.progress.hidden = true;
    updateBatchUi();
  }
}

